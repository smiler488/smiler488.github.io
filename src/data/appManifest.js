export function getAppById(id) {
  return APP_MANIFEST.find((app) => app.id === id);
}

// Display fields are { en, zh } pairs; routes, ids and keywords stay single
// strings because they are read by the router and the search index.
export function localizeApp(value, isChinese) {
  if (value === undefined || value === null) return value;
  if (typeof value === "string" || Array.isArray(value)) return value;
  return isChinese ? value.zh : value.en;
}
